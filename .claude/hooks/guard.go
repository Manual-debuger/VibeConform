// Command guard is the PreToolUse guard Claude Code and Codex call through
// "task -x hook:guard". It reads one tool call as JSON on stdin, matches it
// against the rules in the policy file named by its only argument, and
// denies by exiting 2 with the reason on stderr. Anything else exits 0.
//
// The repository may add a policy.local.json next to the policy file: extra
// deny rules, and exceptions that each lift one rule for the commands or
// paths a pattern matches in full. A local file the guard cannot use
// blocks every call. See docs/specs/0050-guard-exceptions.md.
//
// Generated by VibeConform (prod-go/v1, repo-tooling). The Node and Python
// guards in prod-ts and prod-py implement the same contract; a shared test
// corpus keeps the three in agreement. See
// docs/specs/0021-agent-hooks-task-interface.md in the VibeConform
// repository.
//
// Standard library only, so "go run" needs nothing downloaded. It lives
// under .claude/, which go build ./..., go vet, and golangci-lint all skip,
// so it never becomes part of this repository's own module.
package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
)

// exitDeny is the exit code both agents read as "block this tool call".
const exitDeny = 2

type rule struct {
	ID      string `json:"id"`
	Field   string `json:"field"`
	Pattern string `json:"pattern"`
	Raw     string `json:"raw"`
	Message string `json:"message"`
}

type policy struct {
	Version int                 `json:"version"`
	Tools   map[string][]string `json:"tools"`
	Rules   []rule              `json:"rules"`
	// Exceptions come from the local file only.
	Exceptions []exception `json:"-"`
}

// exception lifts the rule named Rule for a value Pattern matches in full.
type exception struct {
	Rule    string `json:"rule"`
	Pattern string `json:"pattern"`
}

// localName is the repository's own policy file, next to the managed one.
const localName = "policy.local.json"

type toolCall struct {
	ToolName  string         `json:"tool_name"`
	ToolInput map[string]any `json:"tool_input"`
}

func main() {
	if len(os.Args) != 2 {
		deny("guard: usage: guard <policy.json>; blocking until the hook:guard task is fixed")
	}
	p, err := loadPolicy(os.Args[1])
	if err != nil {
		// Fail closed: a guard that cannot read its policy cannot tell a
		// destructive command from a safe one.
		deny(fmt.Sprintf("guard: %v; blocking until the policy file is fixed", err))
	}
	local := filepath.Join(filepath.Dir(os.Args[1]), localName)
	if err := addLocal(p, local); err != nil {
		// Fail closed here too: ignoring the file would drop its rules.
		deny(fmt.Sprintf("guard: %s: %v; every tool call is blocked until it is fixed. "+
			"Ask the user to fix it (in Claude Code: ! <command>, or their editor).", filepath.ToSlash(local), err))
	}

	stdin, err := io.ReadAll(os.Stdin)
	if err != nil {
		deny(fmt.Sprintf("guard: reading stdin: %v", err))
	}

	if msg, ok := check(p, stdin); ok {
		deny(msg)
	}
}

func loadPolicy(path string) (*policy, error) {
	data, err := os.ReadFile(path) // #nosec G304 G703 -- the path is the hook:guard task's own fixed argument
	if err != nil {
		return nil, fmt.Errorf("reading policy: %w", err)
	}
	var p policy
	if err := json.Unmarshal(data, &p); err != nil {
		return nil, fmt.Errorf("parsing policy %s: %w", path, err)
	}
	if p.Version != 1 {
		return nil, fmt.Errorf("policy %s has version %d; this guard understands version 1", path, p.Version)
	}
	return &p, nil
}

// addLocal adds the rules and exceptions of the local file at path to p.
// An absent file adds nothing; any other problem is an error.
func addLocal(p *policy, path string) error {
	data, err := os.ReadFile(path) // #nosec G304 G703 -- a fixed name next to the policy file
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("reading: %w", err)
	}
	var top map[string]json.RawMessage
	if err := json.Unmarshal(data, &top); err != nil || top == nil {
		return errors.New("not a JSON object")
	}
	for key := range top {
		if key != "version" && key != "rules" && key != "exceptions" {
			return fmt.Errorf("unknown key %q; only version, rules and exceptions are allowed", key)
		}
	}
	var version int
	if err := json.Unmarshal(top["version"], &version); err != nil || version != 1 {
		return errors.New("version is not 1, the only version this guard understands")
	}
	rules, err := objects(top, "rules")
	if err != nil {
		return err
	}
	for i, r := range rules {
		var nr rule
		for _, f := range []struct {
			key string
			dst *string
		}{{"id", &nr.ID}, {"field", &nr.Field}, {"pattern", &nr.Pattern}, {"message", &nr.Message}} {
			v, ok := r[f.key].(string)
			if !ok || v == "" {
				return fmt.Errorf("rule %d has no %s", i+1, f.key)
			}
			*f.dst = v
		}
		if _, ok := p.Tools[nr.Field]; !ok {
			return fmt.Errorf("rule %s has field %q, which the policy does not know", nr.ID, nr.Field)
		}
		nr.Raw = nr.Pattern
		if raw, ok := r["raw"].(string); ok && raw != "" {
			nr.Raw = raw
		}
		p.Rules = append(p.Rules, nr)
	}
	exceptions, err := objects(top, "exceptions")
	if err != nil {
		return err
	}
	for i, e := range exceptions {
		id, _ := e["rule"].(string)
		pattern, _ := e["pattern"].(string)
		if id == "" || pattern == "" {
			return fmt.Errorf("exception %d needs a rule and a pattern", i+1)
		}
		p.Exceptions = append(p.Exceptions, exception{Rule: id, Pattern: pattern})
	}
	return nil
}

// objects decodes top[key], when present, as a list of objects.
func objects(top map[string]json.RawMessage, key string) ([]map[string]any, error) {
	raw, ok := top[key]
	if !ok {
		return nil, nil
	}
	var list []map[string]any
	if err := json.Unmarshal(raw, &list); err != nil || list == nil || slices.ContainsFunc(list, func(m map[string]any) bool { return m == nil }) {
		return nil, fmt.Errorf("%s is not a list of objects", key)
	}
	return list, nil
}

// excepted reports whether an exception lifts rule r for value. A pattern
// that does not compile lifts nothing.
func excepted(p *policy, r rule, value string) bool {
	for _, e := range p.Exceptions {
		if e.Rule != r.ID {
			continue
		}
		if re, err := regexp.Compile("^(?:" + e.Pattern + ")$"); err == nil && re.MatchString(value) {
			return true
		}
	}
	return false
}

// check returns the message of the first rule the tool call matches.
//
// The parsed field is matched when the payload parses, names a known tool,
// and carries that tool's field as a string. Otherwise every rule's raw
// pattern is matched against the payload text, which is exactly what the
// bash hooks did before this guard replaced them: never less strict.
// Exceptions apply to the parsed field only.
func check(p *policy, stdin []byte) (string, bool) {
	var call toolCall
	if err := json.Unmarshal(stdin, &call); err == nil {
		if field, ok := fieldFor(p, call.ToolName); ok {
			if value, ok := call.ToolInput[field].(string); ok {
				for _, r := range p.Rules {
					if r.Field == field && matches(r.Pattern, value) && !excepted(p, r, value) {
						return r.Message, true
					}
				}
				return "", false
			}
		}
	}

	text := string(stdin)
	for _, r := range p.Rules {
		if matches(r.Raw, text) {
			return r.Message, true
		}
	}
	return "", false
}

func fieldFor(p *policy, toolName string) (string, bool) {
	for field, tools := range p.Tools {
		if slices.Contains(tools, toolName) {
			return field, true
		}
	}
	return "", false
}

// matches reports whether pattern matches s. A pattern that does not
// compile counts as a match: a broken rule must block rather than quietly
// stop guarding.
func matches(pattern, s string) bool {
	re, err := regexp.Compile(pattern)
	if err != nil {
		return true
	}
	return re.MatchString(s)
}

func deny(msg string) {
	_, _ = fmt.Fprintln(os.Stderr, msg)
	os.Exit(exitDeny)
}
